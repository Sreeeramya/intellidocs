"use client";

import { useState } from "react";
import Link from "next/link";
import {
  ArrowDownToLine,
  BookOpen,
  CheckCircle2,
  ChevronRight,
  FileText,
  Plus,
  Search,
  ShieldCheck,
} from "lucide-react";
import { PageHeading, StatusBadge } from "./shared";
const reports = [
  {
    title: "Q3 2024 Market Trends & Outlook",
    date: "Oct 24, 2024",
    sources: 8,
    tag: "Market research",
  },
  {
    title: "Competitive Landscape Analysis",
    date: "Oct 21, 2024",
    sources: 12,
    tag: "Competitive analysis",
  },
  {
    title: "Customer Retention Benchmark",
    date: "Oct 18, 2024",
    sources: 6,
    tag: "Benchmark",
  },
];

export function ReportsPage() {
  const [selected, setSelected] = useState(0);
  const [reportsList, setReportsList] = useState(reports);
  return (
    <div className="content">
      <PageHeading
        eyebrow="SAVED RESEARCH"
        title="Reports"
        sub="Review and export your completed research."
        action={
          <Link href="/research" className="outline-button">
            <Plus size={15} /> New research
          </Link>
        }
      />
      <div className="reports-grid">
        <section className="report-list">
          <div className="list-heading">
            <b>
              All reports{" "}
              <span className="count-chip">{reportsList.length}</span>
            </b>
            <Search size={15} />
          </div>
          {reportsList.map((r, i) => (
            <button
              key={r.title}
              className={`report-item ${selected === i ? "report-selected" : ""}`}
              onClick={() => setSelected(i)}
            >
              <span className="report-icon">
                <FileText size={17} />
              </span>
              <span className="report-item-copy">
                <b>{r.title}</b>
                <small>
                  {r.date} · {r.sources} sources
                </small>
                <em>{r.tag}</em>
              </span>
              <ChevronRight size={15} />
            </button>
          ))}
          {reportsList.length === 0 && (
            <div className="empty-state compact">
              <FileText size={20} />
              <b>No reports yet</b>
              <p>Completed research reports will appear here.</p>
            </div>
          )}
        </section>
        <section className="report-viewer">
          <div className="viewer-toolbar">
            <span>
              <span className="ready-dot" /> Saved report
            </span>
            <button
              className="outline-button small-button"
              onClick={() => {
                const r = reportsList[selected];
                if (!r) return;
                const blob = new Blob(
                  [
                    `${r.title}\n\nGenerated by IntelliDocs · ${r.date}\n\nExecutive summary\nThis sample report synthesizes findings from ${r.sources} source documents. Revenue growth, changing customer needs, and operational efficiency are the key themes identified across the materials.\n\nKey findings\n• Growth is strongest in recurring revenue segments.\n• Customer retention remains a meaningful opportunity.\n• Regional expansion is contributing to overall performance.\n\nSources\n${r.sources} source documents reviewed.`,
                  ],
                  { type: "text/plain" },
                );
                const url = URL.createObjectURL(blob);
                const a = document.createElement("a");
                a.href = url;
                a.download = `${r.title.toLowerCase().replaceAll(" ", "-")}.txt`;
                a.click();
                URL.revokeObjectURL(url);
              }}
            >
              <ArrowDownToLine size={14} /> Download
            </button>
          </div>
          {reportsList.length > 0 && reportsList[selected] ? (
            <article className="report-document">
              <div className="report-kicker">
                INTELLIDOCS RESEARCH BRIEF <span>·</span>{" "}
                {reportsList[selected].date.toUpperCase()}
              </div>
              <h2>{reportsList[selected].title}</h2>
              <p className="report-deck">
                A synthesized analysis grounded in your documents, with verified
                insights and traceable sources.
              </p>
              <div className="report-meta">
                <span>
                  <FileText size={13} />
                  {reportsList[selected].sources} sources
                </span>
                <span>
                  <CheckCircle2 size={13} /> Verified citations
                </span>
              </div>
              <div className="report-rule" />
              <h3>Executive summary</h3>
              <p>
                This report synthesizes findings across{" "}
                {reportsList[selected].sources} source documents. Revenue
                growth, changing customer needs, and operational efficiency
                emerge as the defining themes in the materials reviewed.
              </p>
              <p>
                Organizations are prioritizing recurring revenue, strengthening
                customer retention, and investing in new markets. The evidence
                points to durable momentum, while highlighting areas that
                warrant continued attention.
              </p>
              <h3>Key findings</h3>
              <div className="finding">
                <span>01</span>
                <p>
                  <b>Recurring revenue is accelerating.</b> Subscription growth
                  consistently outpaces services revenue across the reviewed
                  materials.
                </p>
              </div>
              <div className="finding">
                <span>02</span>
                <p>
                  <b>Retention is a strategic lever.</b> Improvements in
                  customer expansion have an outsized effect on overall
                  performance.
                </p>
              </div>
              <div className="finding">
                <span>03</span>
                <p>
                  <b>Expansion creates new opportunities.</b> New geographic
                  markets add meaningful growth and diversify revenue.
                </p>
              </div>
              <div className="report-source-box">
                <ShieldCheck size={16} />
                <span>
                  All findings are traceable to{" "}
                  <b>{reportsList[selected].sources} verified sources</b> in
                  your document library.
                </span>
                <button onClick={() => {}}>View sources</button>
              </div>
            </article>
          ) : (
            <div className="empty-state">
              <BookOpen size={22} />
              <b>Select a report</b>
              <p>Choose a report from the list to view it.</p>
            </div>
          )}
        </section>
      </div>
    </div>
  );
}
